-- 7. Verifikasi
SELECT
  (SELECT COUNT(*) FROM archived_reports) AS total_arsip,
  (SELECT COUNT(*) FROM archived_reports WHERE is_deleted = false) AS arsip_aktif,
  (SELECT COUNT(*) FROM archive_activity_logs) AS total_log_aktivitas;
